let language = "vi";
const originals = new WeakMap();
const attributes = new WeakMap();

export function getLanguage() { return language; }
export function setLanguage(next) {
  language = next === "en" ? "en" : "vi";
  return language;
}

export function t(value) {
  if (language !== "en" || typeof value !== "string") return value;
  const exact = en[value];
  if (exact) return exact;
  // Interpolated validation messages.
  let match = /^Cần nhập (.+)\.$/.exec(value);
  if (match) return "Please enter " + (en[match[1]] ?? match[1]) + ".";
  match = /^Thời gian (.+) chưa hợp lệ\.$/.exec(value);
  if (match) return "Invalid " + (en[match[1]] ?? match[1]) + ".";
  match = /^Thời gian (.+) không hợp lệ\.$/.exec(value);
  if (match) return "Invalid " + (en[match[1]] ?? match[1]) + ".";
  match = /^Nút (\d+) cần cả tên và URL\.$/.exec(value);
  if (match) return "Button " + match[1] + " requires both a label and a URL.";
  match = /^URL không thuộc nền tảng (.+)\. Hãy kiểm tra đường dẫn\.$/.exec(value);
  if (match) return "The URL does not belong to " + match[1] + ". Check the link.";
  // Extra QR link type hints; prefix is from the localized catalog above.
  const suffix = ". QR chỉ chứa liên kết: để người quét mở được tài liệu/trang, nội dung phải được hosting ở nơi họ có quyền truy cập.";
  if (value.endsWith(suffix)) return (en[value.slice(0, -suffix.length)] ?? value.slice(0, -suffix.length)) +
    ". " + en[suffix.slice(2)];
  // Dynamic status showing exact output dimensions.
  match = /^Ảnh xuất: (\d+) × (\d+) px \(PNG \/ SVG\)\.(.*)$/.exec(value);
  if (match) return "Export image: " + match[1] + " × " + match[2] + " px (PNG / SVG)." +
    (match[3] ? t(match[3]) : "");
  return value;
}

// Reversible translator. Works on dynamically appended forms and message nodes.
// It deliberately avoids any editable input values, SVG QR artwork and printed user data.
function translateNode(node) {
  const raw = node.nodeValue;
  if (!raw || !raw.trim()) return;
  const prev = originals.get(node);
  if (!prev || prev.lastRendered !== raw) {
    originals.set(node, {vi: raw, lastRendered: raw});
  }
  const original = originals.get(node);
  const translated = language === "vi" ? original.vi
    : original.vi.replace(/^(\s*)([\s\S]*?)(\s*)$/, (_, pre, middle, post) => pre + t(middle) + post);
  if (node.nodeValue !== translated) node.nodeValue = translated;
  original.lastRendered = translated;
}
function translateAttribute(node, attr) {
  if (!node.hasAttribute(attr)) return;
  let record = attributes.get(node);
  if (!record) { record = {}; attributes.set(node, record); }
  const value = node.getAttribute(attr);
  if (!record[attr] || record[attr].lastRendered !== value)
    record[attr] = {vi:value, lastRendered:value};
  const translated = language === "vi" ? record[attr].vi : t(record[attr].vi);
  if (value !== translated) node.setAttribute(attr, translated);
  record[attr].lastRendered = translated;
}
export function translateDom(root = document.body) {
  if (!root) return;
  const process = (node) => {
    if (!node) return;
    if (node.nodeType === 3) {
      const p = node.parentElement;
      if (p?.closest("svg, code, script, style, #qr, #wifi-ssid-preview, #wifi-password-preview")) return;
      translateNode(node);
    }
    if (node.nodeType === 1) {
      for (const attr of ["placeholder","title","aria-label","label"]) translateAttribute(node,attr);
    }
  };
  process(root);
  if (!root.ownerDocument) return;
  const walker = root.ownerDocument.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) process(walker.currentNode);
  const title = document.title;
  const titleEn = en["QRFrame Nội Bộ — Tạo mã QR đa chức năng"];
  document.title = language === "en" ? titleEn : "QRFrame Nội Bộ — Tạo mã QR đa chức năng";
  document.documentElement.lang = language;
  const description = document.querySelector('meta[name="description"]');
  if (description) translateAttribute(description, "content");
}
